import Foundation

/// A multiple-choice question backed by a PubMed publication.
public struct Question: Codable, Hashable, Identifiable, Sendable {
    public static let optionCount = 4

    /// Unique per language, e.g. `micro-001-en`.
    public var id: String
    /// Shared by all translations of the same question, e.g. `micro-001`.
    public var translationKey: String
    public var language: AppLanguage
    public var category: ScienceCategory
    public var difficulty: Difficulty
    public var prompt: String
    /// Exactly four options.
    public var options: [String]
    public var correctOptionIndex: Int
    /// Scientific explanation shown after answering.
    public var explanation: String
    /// One-line explanation for small screens (Apple Watch).
    public var shortExplanation: String?
    /// Source publication. `source.pmid` identifies the article the question comes from.
    public var source: ArticleReference
    public var verification: SourceVerification

    public init(
        id: String,
        translationKey: String,
        language: AppLanguage,
        category: ScienceCategory,
        difficulty: Difficulty,
        prompt: String,
        options: [String],
        correctOptionIndex: Int,
        explanation: String,
        shortExplanation: String? = nil,
        source: ArticleReference,
        verification: SourceVerification
    ) {
        self.id = id
        self.translationKey = translationKey
        self.language = language
        self.category = category
        self.difficulty = difficulty
        self.prompt = prompt
        self.options = options
        self.correctOptionIndex = correctOptionIndex
        self.explanation = explanation
        self.shortExplanation = shortExplanation
        self.source = source
        self.verification = verification
    }

    public var correctAnswer: String { options[correctOptionIndex] }

    /// `true` for questions generated on demand and only checked automatically against their source.
    /// The UI must label these; only `.verified` questions may be presented as reviewed.
    public var isAutoGenerated: Bool { verification.status == .autoVerified }

    public func isCorrect(_ optionIndex: Int) -> Bool { optionIndex == correctOptionIndex }
}

/// Records whether — and how — a question's correct answer was checked against its source.
public struct SourceVerification: Codable, Hashable, Sendable {
    public enum Status: String, Codable, Sendable {
        /// Not checked yet. Never playable.
        case pending
        /// Passed automated checks but is held for human review. Never playable.
        case needsReview
        /// Generated on demand: the supporting excerpt was found verbatim in the source by an
        /// automatic check, but no expert reviewed the question. Playable, always labeled as such.
        case autoVerified
        /// The supporting excerpt was found in the source and the question was reviewed.
        case verified
        /// Ambiguous, incorrect or unverifiable. Discarded.
        case rejected
    }

    public enum Method: String, Codable, Sendable {
        /// Written and checked by an editor against the source abstract.
        case editorialReview
        /// Generated by the question service; only the excerpt match was automated.
        case automatedEvidenceMatch
    }

    public var status: Status
    public var method: Method
    /// Verbatim passage from the source's title or abstract that supports the correct answer.
    public var supportingExcerpt: String?
    public var reviewedAt: Date?

    public init(status: Status, method: Method, supportingExcerpt: String?, reviewedAt: Date? = nil) {
        self.status = status
        self.method = method
        self.supportingExcerpt = supportingExcerpt
        self.reviewedAt = reviewedAt
    }
}
